"""One-time-safe setup of the Firebase pieces the order system needs.

Runs inside the deploy workflow. Safe to run again and again: it only creates what is missing.
  1. turns on the Google APIs that Firebase needs
  2. makes sure the project has a web app, and writes its public settings to firebase-config.js
  3. makes sure the Firestore database exists (Hong Kong region)
Nothing secret is printed.
"""
import json, os, sys, time
import google.auth.transport.requests
from google.oauth2 import service_account
import requests

key_path = os.environ["GOOGLE_APPLICATION_CREDENTIALS"]
creds = service_account.Credentials.from_service_account_file(
    key_path, scopes=["https://www.googleapis.com/auth/cloud-platform"])
pid = creds.project_id
H = {}

def token():
    creds.refresh(google.auth.transport.requests.Request())
    H["Authorization"] = "Bearer " + creds.token
    H["Content-Type"] = "application/json"

def call(method, url, **kw):
    r = requests.request(method, url, headers=H, timeout=60, **kw)
    return r

def wait(op_url, label):
    for _ in range(60):
        r = call("GET", op_url)
        if r.ok and r.json().get("done"):
            if "error" in r.json():
                print(f"::warning::{label} failed: {r.json()['error'].get('message')}")
                return None
            return r.json()
        time.sleep(3)
    print(f"::warning::{label} timed out")
    return None

token()
print("project:", pid)

# 1. APIs
apis = ["firestore.googleapis.com", "firebaserules.googleapis.com", "firebase.googleapis.com", "identitytoolkit.googleapis.com"]
r = call("POST", f"https://serviceusage.googleapis.com/v1/projects/{pid}/services:batchEnable", json={"serviceIds": apis})
print("enable APIs:", r.status_code if not r.ok else "ok")
if not r.ok:
    print("::warning::Could not enable APIs automatically:", r.text[:300])
else:
    op = r.json().get("name")
    if op:
        wait(f"https://serviceusage.googleapis.com/v1/{op}", "enable APIs")

# 2. web app + config
base = f"https://firebase.googleapis.com/v1beta1/projects/{pid}"
r = call("GET", base + "/webApps")
if not r.ok:
    print("::error::Cannot list web apps:", r.status_code, r.text[:400])
    sys.exit(1)
apps = r.json().get("apps", [])
if not apps:
    print("creating web app")
    r = call("POST", base + "/webApps", json={"displayName": "mhkpop-website"})
    if not r.ok:
        print("::error::Cannot create web app:", r.status_code, r.text[:400])
        sys.exit(1)
    done = wait(f"https://firebase.googleapis.com/v1beta1/{r.json()['name']}", "create web app")
    r = call("GET", base + "/webApps")
    apps = r.json().get("apps", [])
if not apps:
    print("::error::No web app available")
    sys.exit(1)
app_id = apps[0]["appId"]
r = call("GET", f"{base}/webApps/{app_id}/config")
if not r.ok:
    print("::error::Cannot read web app config:", r.status_code, r.text[:400])
    sys.exit(1)
c = r.json()
keep = {k: c[k] for k in ("apiKey", "authDomain", "projectId", "storageBucket", "messagingSenderId", "appId", "measurementId") if c.get(k)}
with open("firebase-config.js", "w") as f:
    f.write("// Generated by the deploy workflow. These settings are public by design; security comes from firestore.rules.\n")
    f.write("window.FIREBASE_CONFIG = " + json.dumps(keep, indent=2) + ";\n")
print("wrote firebase-config.js for web app", app_id)

# 3. Firestore database
db = f"https://firestore.googleapis.com/v1/projects/{pid}/databases"
r = call("GET", db + "/(default)")
if r.status_code == 404 or (r.ok is False and "NOT_FOUND" in r.text):
    print("creating Firestore database (asia-east2, Hong Kong)")
    r = call("POST", db + "?databaseId=(default)", json={"type": "FIRESTORE_NATIVE", "locationId": "asia-east2"})
    if not r.ok:
        print("::warning::Could not create the Firestore database automatically:", r.status_code, r.text[:400])
    else:
        wait(f"https://firestore.googleapis.com/v1/{r.json()['name']}", "create Firestore database")
elif r.ok:
    print("Firestore database already exists")
else:
    print("::warning::Could not check Firestore:", r.status_code, r.text[:300])
